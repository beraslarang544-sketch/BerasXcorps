import JSZip from "jszip";
import {
  encodeAxml,
  el,
  aStr,
  androidStr,
  androidInt,
  androidBool,
} from "./axml.js";

function dexStub() {
  const buf = Buffer.alloc(0x70);
  buf.write("dex\n035\0", 0, 8, "binary");
  buf.writeUInt32LE(0x70, 32);
  buf.writeUInt32LE(0x70, 36);
  buf.writeUInt32LE(0x12345678, 40);
  buf.writeUInt32LE(0, 96);
  return buf;
}

function elfStub(machine = 183) {
  const buf = Buffer.alloc(64, 0);
  buf[0] = 0x7f;
  buf.write("ELF", 1, 3, "ascii");
  buf[4] = machine === 40 || machine === 3 ? 1 : 2; // 32-bit ARM / x86, else 64
  buf[5] = 1;
  buf[6] = 1;
  buf.writeUInt16LE(3, 16); // ET_DYN
  buf.writeUInt16LE(machine, 18);
  buf.writeUInt32LE(1, 20);
  return buf;
}

export async function buildSampleApk() {
  const manifest = encodeAxml(
    el(
      "manifest",
      [
        aStr("package", "id.berasxcorps.farm"),
        androidInt("versionCode", 100),
        androidStr("versionName", "1.0.0-hex"),
        androidInt("compileSdkVersion", 34),
        androidStr("compileSdkVersionCodename", "14"),
      ],
      [
        el("uses-sdk", [androidInt("minSdkVersion", 24), androidInt("targetSdkVersion", 34)]),
        el("uses-permission", [androidStr("name", "android.permission.INTERNET")]),
        el("uses-permission", [androidStr("name", "android.permission.VIBRATE")]),
        el(
          "application",
          [
            androidStr("name", "id.berasxcorps.farm.FarmApp"),
            androidStr("label", "BerasFarm"),
            androidBool("debuggable", true),
            androidBool("allowBackup", true),
            androidBool("hardwareAccelerated", true),
            androidBool("extractNativeLibs", false),
          ],
          [
            el("activity", [
              androidStr("name", "id.berasxcorps.farm.MainActivity"),
              androidBool("exported", true),
            ]),
            el("service", [
              androidStr("name", "id.berasxcorps.hex.BridgeService"),
              androidBool("exported", false),
            ]),
          ]
        ),
      ]
    )
  );

  const zip = new JSZip();
  zip.file("AndroidManifest.xml", manifest);
  zip.file("classes.dex", dexStub());
  zip.file("lib/arm64-v8a/libberas.so", elfStub(183));
  zip.file("lib/armeabi-v7a/libberas.so", elfStub(40));
  zip.file(
    "assets/game/schema.json",
    JSON.stringify(
      {
        name: "BerasFarm",
        package: "id.berasxcorps.farm",
        fields: [
          { id: "coins", type: "i32", offset: "0x1A000" },
          { id: "gems", type: "i32", offset: "0x1A004" },
          { id: "health", type: "f32", offset: "0x1A008" },
          { id: "speed", type: "f32", offset: "0x1A010" },
        ],
      },
      null,
      2
    )
  );
  zip.file(
    "assets/xcorps/README.txt",
    "Sample first-party APK generated by HEX Studio. Safe to inject again.\n"
  );
  zip.file("res/layout/activity_main.xml", "<LinearLayout/>\n");
  zip.file("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nCreated-By: BerasXcorps HEX\n");

  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
}
